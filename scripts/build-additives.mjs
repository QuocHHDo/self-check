// Builds js/additives-data.js from the Open Food Facts additive taxonomy (ODbL), so the app can name the
// additives on a scanned product without any network call.
//   git clone --depth 1 --filter=blob:none --sparse https://github.com/openfoodfacts/openfoodfacts-server off
//   (cd off && git sparse-checkout set taxonomies)
//   node scripts/build-additives.mjs off/taxonomies
// Keeps, per E-number: English name, functions (classes), and whether EFSA's re-evaluation found a high risk that
// some people exceed the acceptable daily intake.
import fs from "node:fs";
import path from "node:path";

const dir = process.argv[2];
if (!dir) { console.error("usage: node scripts/build-additives.mjs <openfoodfacts-server>/taxonomies"); process.exit(1); }
const read = f => fs.readFileSync(path.join(dir, f), "utf8");
const blocks = text => text.split(/\n\s*\n/).map(b => b.split("\n").filter(l => l && !l.startsWith("#")));
const idOf = name => "en:" + name.trim().toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

// Function classes: en:emulsifier → "emulsifier"
const CLASS = {};
for (const b of blocks(read("additives_classes.txt"))) {
  const en = b.find(l => l.startsWith("en:") && !l.startsWith("en:en"));
  if (en) { const first = en.slice(3).split(",")[0].trim(); CLASS[idOf(first)] = first.toLowerCase(); }
}

const AMBIGUOUS = new Set(["caramel", "paprika", "turmeric", "curcuma", "saffron", "beetroot", "charcoal", "carbon", "salt", "sugar", "starch",
  "vinegar", "water", "nitrogen", "oxygen", "argon", "helium", "chlorophyll", "lutein", "carotene", "beta-carotene", "riboflavin", "gold", "silver",
  "iron", "calcium", "magnesium", "zinc", "honey", "shellac", "wax", "beeswax", "gelatin", "glycerin", "glycerol", "lactose", "sorbitol syrup", "maltitol syrup",
  "polydextrose", "inulin", "cellulose", "dextrin", "dextrins", "pectin", "pectins", "agar", "guar", "gum", "lecithin", "lecithins", "malic", "lactic",
  // grains, minerals, vitamins and lab words that name something else in an ingredient list
  "amaranth", "aluminium", "aluminum", "ammonia", "bengal", "ceylon", "chlorine", "ethanol", "hydrogen", "linear", "niacin", "nicotinamide",
  "riboflavins", "leucine", "l-leucine", "tannin", "lycopene", "gelatine", "glycerine", "propane", "butane", "isobutane", "peptone", "tryptone",
  "selenite", "magnesia", "sylvine", "kaolin", "talc", "talcum", "urea", "sandalwood", "alpha-tocopherol", "d-alpha-tocopherol", "dl-alpha-tocopherol"]);
const out = {};
for (const b of blocks(read("additives.txt"))) {
  const en = b.find(l => /^en: ?E\d/i.test(l));
  if (!en) continue;
  const names = en.slice(3).split(",").map(s => s.trim()).filter(Boolean);
  const code = names[0].toLowerCase(); // e322, e322i, e150d
  if (!/^e\d{3,4}[a-z]*$/.test(code)) continue;
  const prop = k => (b.find(l => l.startsWith(k + ":en:")) || "").slice(k.length + 4).trim();
  const classes = prop("additives_classes").split(",").map(s => CLASS[s.trim()] || null).filter(Boolean);
  // Names to find in a US ingredient list (USDA Branded has text, not E-number tags): "red 40", "xanthan gum".
  // Single everyday words that are also additive names (caramel, paprika, turmeric) would give false matches.
  const terms = [...new Set(names.slice(1).map(t => t.toLowerCase().replace(/\s+/g, " ").trim()))]
    .filter(t => t.length >= 4 && /[a-z]/.test(t) && !/^e[ -]?\d/.test(t) && !AMBIGUOUS.has(t) && !/^c\.?i\.? \d/.test(t) && !/^(vitamin|provitamin)\b/.test(t) && !/[\\()]/.test(t));
  const entry = [names[1] || names[0].toUpperCase(), [...new Set(classes)].join(", "), prop("efsa_evaluation_overexposure_risk") === "en:high" ? 1 : 0];
  if (terms.length) entry.push(terms.slice(0, 12).join("|"));
  out[code] = entry;
}
const n = Object.keys(out).length;
if (n < 300) { console.error(`only ${n} additives parsed; is ${dir} the taxonomies folder?`); process.exit(1); }
const body = `// Generated by scripts/build-additives.mjs from the Open Food Facts additive taxonomy
// (https://github.com/openfoodfacts/openfoodfacts-server/tree/main/taxonomies, ODbL). Don't edit by hand.
// code → [English name, functions, 1 if EFSA's re-evaluation found a high risk of exceeding the acceptable daily intake,\n//         names to look for in ingredient text, separated by |]
(function (root, data) {
  if (typeof module === "object" && module.exports) module.exports = data;
  else root.SelfCheckAdditivesData = data;
})(typeof self !== "undefined" ? self : this, ${JSON.stringify(out)});
`;
fs.writeFileSync(new URL("../js/additives-data.js", import.meta.url), body);
console.log(`Wrote js/additives-data.js: ${n} additives, ${(body.length / 1024).toFixed(0)} KB`);
